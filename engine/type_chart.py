def get_effectiveness(attack_type: Type, defense_types: list[Type])-> float:
    if attack_type == Type.UNKNOWN or attack_type == Type.STELLAR:
        return 1.0
    effectiveness = 1.0
    for defense_type in defense_types:
        if defense_type == Type.UNKNOWN or defense_type == Type.STELLAR:
            continue
        effectiveness *= type_matrix[attack_type.value-1][defense_type.value-1]
    return effectiveness


